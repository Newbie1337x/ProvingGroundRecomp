#!/usr/bin/env python3
"""Finds the game's Direct3D entry points in the recompiled code and writes the list the
Direct3D call tracer (src/native/pg_d3d_trace.cpp) hooks.

The Xbox 360 SDK's Direct3D is linked into default.xex with no symbols. It is found from the
kernel's graphics imports (Vd*): the functions that call them sit in one address range with
the rest of Direct3D (0x82560000-0x82594000 for this executable; the C runtime is just before
it and Xam code just after). Its entry points are the functions in that range that game code
outside the libraries calls.

Usage: python tools/native/find_d3d_api.py   (after a build has generated generated/)
"""
import collections
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D3D_RANGE = (0x82560000, 0x82594000)
# Direct3D, the C runtime and Xam: calls between these are library-internal.
LIBRARIES = (0x82550000, 0x825C0000)
OUT = os.path.join(ROOT, 'src', 'native', 'd3d_entry_points.inc')

func_re = re.compile(r'^DEFINE_REX_FUNC\((sub_[0-9A-F]{8})\)', re.M)
call_re = re.compile(r'\b(sub_[0-9A-F]{8})\(ctx, base\)')
vd_re = re.compile(r'\b__imp__Vd[A-Za-z]+\(ctx, base\)')


def address(name):
    return int(name[4:], 16)


def main():
    paths = sorted(glob.glob(os.path.join(ROOT, 'generated', 'pg_recomp.*.cpp')))
    if not paths:
        sys.exit('generated/ is empty: build the game first')
    calls, lines, vd_callers = {}, {}, set()
    for path in paths:
        text = open(path, encoding='utf-8', errors='replace').read()
        starts = [(m.start(), m.group(1)) for m in func_re.finditer(text)]
        for i, (pos, name) in enumerate(starts):
            body = text[pos:starts[i + 1][0] if i + 1 < len(starts) else len(text)]
            calls[name] = set(call_re.findall(body)) - {name}
            lines[name] = body.count('\n')
            if vd_re.search(body):
                vd_callers.add(name)
    lo, hi = D3D_RANGE
    outside = sorted(n for n in vd_callers if not lo <= address(n) < hi)
    if outside:
        print('warning: Vd* callers outside the Direct3D range:', ', '.join(outside))
    callers = collections.defaultdict(set)
    for name, callees in calls.items():
        for callee in callees:
            callers[callee].add(name)

    def in_libraries(name):
        return LIBRARIES[0] <= address(name) < LIBRARIES[1]

    # Functions the game already replaces in src/ can't be wrapped a second time.
    hooked = set()
    for path in glob.glob(os.path.join(ROOT, 'src', '**', '*.cpp'), recursive=True):
        if os.path.basename(path) == 'pg_d3d_trace.cpp':
            continue
        text = open(path, encoding='utf-8', errors='replace').read()
        hooked |= set(re.findall(r'void (sub_[0-9A-F]{8})\(PPCContext', text))
        hooked |= set(re.findall(r'PG_TIMELINE_HOOK\((sub_[0-9A-F]{8})', text))

    entries = []
    for name in sorted(calls, key=address):
        if not lo <= address(name) < hi:
            continue
        game_callers = [c for c in callers[name] if not in_libraries(c)]
        if game_callers:
            entries.append((name, len(game_callers), lines[name]))
    skipped = [e for e in entries if e[0] in hooked]
    entries = [e for e in entries if e[0] not in hooked]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as out:
        out.write("// Generated by tools/native/find_d3d_api.py: the game's Direct3D entry points\n")
        out.write('// (functions in 0x%08X-0x%08X called by game code). Do not edit.\n' % D3D_RANGE)
        out.write('// PG_D3D_ENTRY(function, game callers, lines of generated code)\n')
        for name, count, size in entries:
            out.write('PG_D3D_ENTRY(%s, %d, %d)\n' % (name, count, size))
    print('%d entry points written to %s' % (len(entries), os.path.relpath(OUT, ROOT)))
    if skipped:
        print('already hooked in src/, not traced:', ', '.join(e[0] for e in skipped))


if __name__ == '__main__':
    main()
